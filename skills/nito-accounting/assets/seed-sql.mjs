// Generates the SQL that sets a company up on the ledger schema: the chart,
// the default accounts, twelve periods, the numbering rows and the payment
// journals. Write it to a file and run it in DBeaver (the team's rule: no
// script connects to a shared database by itself).
//
//   // setup.mjs  (a file, run once; it prints SQL and touches no database)
//   import { seedSql } from "./seed-sql.mjs";
//   import chart from "./coa-template-id.json" with { type: "json" };
//   console.log(seedSql({ company_id: 1, fiscal_year: 2026, chart, ... }));
//   node setup.mjs > seed-company-1.sql
//
// Values are escaped for MySQL string literals; review the file before running it.
const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v)
  : `'${String(v).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`);

export function seedSql({ company_id, fiscal_year, chart, defaults, journals, cashbanks = [], fiscalYearStartMonth = 1 }) {
  if (!Number.isInteger(company_id) || !Number.isInteger(fiscal_year)) throw new Error("company_id and fiscal_year must be integers");
  const out = ["-- generated by nito-accounting assets/seed-sql.mjs", "START TRANSACTION;", ""];
  out.push("-- chart of accounts");
  for (const a of chart.accounts) {
    out.push(`INSERT INTO T_M_ACC_ACCOUNT (company_id, account_code, account_name, account_type, normal_balance, control_type, is_postable, is_active) VALUES (${[
      company_id, a.code, a.name, a.type, a.normal_balance, a.control ?? null, a.postable === false ? 0 : 1, 1].map(q).join(", ")});`);
  }
  out.push("", "-- account determination: role key -> account");
  for (const [role, code] of Object.entries(defaults)) {
    if (!chart.accounts.some((a) => a.code === code)) throw new Error(`role ${role} points at ${code}, which is not in the chart`);
    out.push(`INSERT INTO T_M_ACC_DEFAULT_ACCOUNT (company_id, role_key, account_id) SELECT ${q(company_id)}, ${q(role)}, account_id FROM T_M_ACC_ACCOUNT WHERE company_id = ${q(company_id)} AND account_code = ${q(code)};`);
  }
  out.push("", "-- twelve monthly periods, open");
  for (let i = 0; i < 12; i++) {
    const m0 = fiscalYearStartMonth - 1 + i, y = fiscal_year + Math.floor(m0 / 12), m = (m0 % 12) + 1;
    const start = `${y}-${String(m).padStart(2, "0")}-01`, end = new Date(Date.UTC(y, m, 0)).toISOString().slice(0, 10);
    out.push(`INSERT INTO T_M_ACC_PERIOD (company_id, start_date, end_date, status) VALUES (${q(company_id)}, ${q(start)}, ${q(end)}, 'open');`);
  }
  out.push("", "-- numbering: one counter row per journal for the year");
  const codes = [...journals, ...cashbanks.map((c) => c.journal_code)];
  for (const j of new Set(codes)) out.push(`INSERT INTO T_M_ACC_SEQUENCE (company_id, journal_code, fiscal_year, next_number) VALUES (${q(company_id)}, ${q(j)}, ${q(fiscal_year)}, 1);`);
  if (cashbanks.length) out.push("", "-- payment journals");
  for (const c of cashbanks) {
    if (!chart.accounts.some((a) => a.code === c.account)) throw new Error(`payment journal ${c.journal_code} points at ${c.account}, which is not in the chart`);
    out.push(`INSERT INTO T_M_ACC_CASHBANK (company_id, journal_code, name, kind, account_id, bank_name, account_number, currency_code) SELECT ${[
      company_id, c.journal_code, c.name, c.kind, ].map(q).join(", ")}, account_id, ${q(c.bank_name ?? null)}, ${q(c.account_number ?? null)}, ${q(c.currency ?? "IDR")} FROM T_M_ACC_ACCOUNT WHERE company_id = ${q(company_id)} AND account_code = ${q(c.account)};`);
  }
  out.push("", "COMMIT;", "");
  return out.join("\n");
}
